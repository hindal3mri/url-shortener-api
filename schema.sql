
-- =========================================
-- URL Shortener API - Database Schema
-- Authenticated users manage only their own URLs.
-- Public visitors can still use short links and track clicks.
-- =========================================

-- 1. Create the table
CREATE TABLE IF NOT EXISTS public.urls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    long_url TEXT NOT NULL,
    short_code VARCHAR(20) NOT NULL UNIQUE,
    clicks INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_id UUID REFERENCES auth.users(id)
);

-- 2. Upgrade existing table without deleting records
ALTER TABLE public.urls
ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id);

-- 3. Create index for user URLs
CREATE INDEX IF NOT EXISTS urls_user_id_idx
ON public.urls (user_id);

-- 4. Enable RLS
ALTER TABLE public.urls ENABLE ROW LEVEL SECURITY;

-- 5. Remove old policies
DROP POLICY IF EXISTS "Allow public insert" ON public.urls;
DROP POLICY IF EXISTS "Allow public select" ON public.urls;
DROP POLICY IF EXISTS "Users can insert their own URLs" ON public.urls;
DROP POLICY IF EXISTS "Users can view their own URLs" ON public.urls;
DROP POLICY IF EXISTS "Users can delete their own URLs" ON public.urls;

-- 6. Authenticated users can insert their own URLs
CREATE POLICY "Users can insert their own URLs"
ON public.urls
FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

-- 7. Authenticated users can view their own URLs
CREATE POLICY "Users can view their own URLs"
ON public.urls
FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

-- 8. Authenticated users can delete their own URLs
CREATE POLICY "Users can delete their own URLs"
ON public.urls
FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

-- 9. Configure table permissions
REVOKE ALL ON TABLE public.urls FROM PUBLIC;
REVOKE ALL ON TABLE public.urls FROM anon;
REVOKE ALL ON TABLE public.urls FROM authenticated;

GRANT SELECT, INSERT, DELETE
ON TABLE public.urls
TO authenticated;

-- 10. Configure identity sequence permissions
DO $$
DECLARE
    urls_id_sequence TEXT;
BEGIN
    urls_id_sequence := pg_get_serial_sequence('public.urls', 'id');

    IF urls_id_sequence IS NOT NULL THEN
        EXECUTE format(
            'REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon',
            urls_id_sequence
        );

        EXECUTE format(
            'GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated',
            urls_id_sequence
        );
    END IF;
END
$$;

-- 11. Create click tracking function
CREATE OR REPLACE FUNCTION public.increment_url_clicks(p_short_code TEXT)
RETURNS TEXT
LANGUAGE SQL
SECURITY DEFINER
SET search_path = ''
AS $function$
    UPDATE public.urls
    SET clicks = clicks + 1
    WHERE short_code = p_short_code
    RETURNING long_url;
$function$;

-- 12. Configure function permissions
REVOKE ALL ON FUNCTION public.increment_url_clicks(TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.increment_url_clicks(TEXT) FROM anon;
REVOKE ALL ON FUNCTION public.increment_url_clicks(TEXT) FROM authenticated;

GRANT EXECUTE
ON FUNCTION public.increment_url_clicks(TEXT)
TO anon, authenticated;
