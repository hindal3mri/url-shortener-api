
-- =========================================
-- URL Shortener Database Schema
-- =========================================

-- 1. Create URLs table
CREATE TABLE IF NOT EXISTS public.urls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    long_url TEXT NOT NULL,
    short_code VARCHAR(20) NOT NULL UNIQUE,
    clicks INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Enable Row Level Security
ALTER TABLE public.urls ENABLE ROW LEVEL SECURITY;

-- 3. Grant required permissions to anonymous users
GRANT INSERT, SELECT ON TABLE public.urls TO anon;
GRANT USAGE, SELECT ON SEQUENCE public.urls_id_seq TO anon;

-- 4. Configure INSERT policy
DROP POLICY IF EXISTS "Allow public insert" ON public.urls;

CREATE POLICY "Allow public insert"
ON public.urls
FOR INSERT
TO anon
WITH CHECK (true);

-- 5. Configure SELECT policy
DROP POLICY IF EXISTS "Allow public select" ON public.urls;

CREATE POLICY "Allow public select"
ON public.urls
FOR SELECT
TO anon
USING (true);

-- 6. Create click tracking function
CREATE OR REPLACE FUNCTION public.increment_url_clicks(p_short_code text)
RETURNS text
LANGUAGE sql
SECURITY DEFINER
SET search_path TO ''
AS $function$
    UPDATE public.urls
    SET clicks = clicks + 1
    WHERE short_code = p_short_code
    RETURNING long_url;
$function$;

-- 7. Restrict function execution
REVOKE ALL ON FUNCTION public.increment_url_clicks(text) FROM PUBLIC;

-- 8. Allow anonymous users to execute the function
GRANT EXECUTE ON FUNCTION public.increment_url_clicks(text) TO anon;
