
-- =========================================
-- URL Shortener Database Schema
-- Public URL management without authentication
-- =========================================

-- 1. Create URLs table
CREATE TABLE IF NOT EXISTS public.urls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    long_url TEXT NOT NULL,
    short_code VARCHAR(20) NOT NULL UNIQUE,
    clicks INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Remove user ownership column if it exists
ALTER TABLE public.urls
DROP COLUMN IF EXISTS user_id;

-- 3. Enable Row Level Security
ALTER TABLE public.urls ENABLE ROW LEVEL SECURITY;

-- 4. Remove previous policies
DROP POLICY IF EXISTS "Users can insert their own URLs" ON public.urls;
DROP POLICY IF EXISTS "Users can view their own URLs" ON public.urls;
DROP POLICY IF EXISTS "Users can delete their own URLs" ON public.urls;
DROP POLICY IF EXISTS "Allow public insert" ON public.urls;
DROP POLICY IF EXISTS "Allow public select" ON public.urls;
DROP POLICY IF EXISTS "Allow public delete" ON public.urls;

-- 5. Allow public URL creation
CREATE POLICY "Allow public insert"
ON public.urls
FOR INSERT
TO anon
WITH CHECK (true);

-- 6. Allow public URL listing
CREATE POLICY "Allow public select"
ON public.urls
FOR SELECT
TO anon
USING (true);

-- 7. Allow public URL deletion
CREATE POLICY "Allow public delete"
ON public.urls
FOR DELETE
TO anon
USING (true);

-- 8. Grant required table permissions
GRANT SELECT, INSERT, DELETE ON TABLE public.urls TO anon;
GRANT USAGE, SELECT ON SEQUENCE public.urls_id_seq TO anon;

-- 9. Click tracking function
CREATE OR REPLACE FUNCTION public.increment_url_clicks(p_short_code text)
RETURNS text
LANGUAGE sql
SECURITY DEFINER
SET search_path TO ''
AS $function$
    UPDATE public.urls
    SET clicks = clicks + 1
    WHERE short_code = p_short_code
    RETURNING long_url;
$function$;

-- 10. Allow public execution of click tracking
REVOKE ALL ON FUNCTION public.increment_url_clicks(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.increment_url_clicks(text) TO anon;
